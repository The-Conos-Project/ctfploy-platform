def get_lang() -> str:
    lang = session.get("lang") or request.cookies.get(COOKIE_NAME) or DEFAULT_LANG
    return lang if lang in SUPPORTED else DEFAULT_LANG


def set_lang(lang: str) -> None:
    if lang in SUPPORTED:
        session["lang"] = lang


def t(key: str, lang: str | None = None) -> str:
    code = lang or get_lang()
    return MESSAGES.get(code, MESSAGES[DEFAULT_LANG]).get(key) or MESSAGES["en"].get(key, key)
